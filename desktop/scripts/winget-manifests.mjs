#!/usr/bin/env node
/**
 * Writes the winget manifests for a desktop release (`winget install TraceRoost.TraceRoost`):
 *
 *   node desktop/scripts/winget-manifests.mjs --version <v> --assets <dir> --out <dir>
 *
 * `--assets` holds the Windows installers as the GitHub release serves them — signed
 * (`TraceRoost-<v>-win-<arch>.exe`) or preview (`TraceRoost-<v>-win-<arch>-preview.exe`), as
 * desktop-release.yml attached them — and the sha256 of each is computed here from those bytes, so
 * a manifest can only ever install what was published. The three files are written under
 * `<out>/manifests/t/TraceRoost/TraceRoost/<v>/`, the layout microsoft/winget-pkgs uses, which
 * `wingetcreate submit <dir>` takes as is. release.yml's `publish-winget` job runs this after the
 * desktop job; see runbooks/RELEASING.md → "winget".
 *
 * The installer is electron-builder's one-click, per-user NSIS (desktop/electron-builder.cjs):
 * `/S` installs silently, which is winget's default for `nullsoft`; build/installer.nsh asks a
 * running TraceRoost to quit before files are replaced. `ProductCode` is the uninstall key
 * electron-builder derives from the appId, so winget also recognises a copy installed from the
 * downloaded .exe and can upgrade it.
 */

import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { pathToFileURL } from 'node:url'

export const PACKAGE_IDENTIFIER = 'TraceRoost.TraceRoost'
export const MANIFEST_VERSION = '1.12.0'
/** electron-builder's NSIS uninstall key: UUID v5 of appId `com.traceroost.desktop` in its namespace. */
export const PRODUCT_CODE = 'e9b4049e-fb84-5737-95be-668cc3f878b1'
const REPO = 'traceroost/core'
const ARCHES = ['x64', 'arm64']

function usage() {
  console.error('usage: node desktop/scripts/winget-manifests.mjs --version <v> --assets <dir> --out <dir>')
  process.exit(2)
}

/** The installer for `arch` in `files`: the signed name if present, else the preview one. */
export function installerFor(files, version, arch) {
  const signed = `TraceRoost-${version}-win-${arch}.exe`
  const preview = `TraceRoost-${version}-win-${arch}-preview.exe`
  if (files.includes(signed)) return signed
  if (files.includes(preview)) return preview
  return undefined
}

const header = (type) =>
  `# Generated by traceroost/core desktop/scripts/winget-manifests.mjs — don't edit by hand.\n` +
  `# yaml-language-server: $schema=https://aka.ms/winget-manifest.${type}.${MANIFEST_VERSION}.schema.json\n\n`

/** The three manifests, by file name. `installers` is `[{ arch, url, sha256 }]`. */
export function manifests({ version, releaseDate, installers }) {
  const id = PACKAGE_IDENTIFIER
  const versionManifest = header('version') +
`PackageIdentifier: ${id}
PackageVersion: ${version}
DefaultLocale: en-US
ManifestType: version
ManifestVersion: ${MANIFEST_VERSION}
`
  const installerManifest = header('installer') +
`PackageIdentifier: ${id}
PackageVersion: ${version}
InstallerType: nullsoft
Scope: user
InstallModes:
- interactive
- silent
UpgradeBehavior: install
ProductCode: ${PRODUCT_CODE}
ReleaseDate: ${releaseDate}
AppsAndFeaturesEntries:
- DisplayName: TraceRoost
  ProductCode: ${PRODUCT_CODE}
Installers:
${installers.map(i => `- Architecture: ${i.arch}
  InstallerUrl: ${i.url}
  InstallerSha256: ${i.sha256.toUpperCase()}
`).join('')}ManifestType: installer
ManifestVersion: ${MANIFEST_VERSION}
`
  const localeManifest = header('defaultLocale') +
`PackageIdentifier: ${id}
PackageVersion: ${version}
PackageLocale: en-US
Publisher: TraceRoost
PublisherUrl: https://traceroost.com
PublisherSupportUrl: https://github.com/${REPO}/issues
PackageName: TraceRoost
PackageUrl: https://traceroost.com
License: MIT
LicenseUrl: https://github.com/${REPO}/blob/v${version}/LICENSE
ShortDescription: Local monitoring for AI coding agents — traces, cost and stuck-agent signals.
Description: |-
  TraceRoost records what your coding agents (Claude Code, Codex, GitHub Copilot) did, what it cost
  and what landed, and shows it in a dashboard on this machine. The desktop app runs the collector
  from the notification area.
Moniker: traceroost
Tags:
- ai
- claude-code
- codex
- copilot
- observability
- opentelemetry
- telemetry
ReleaseNotesUrl: https://github.com/${REPO}/releases/tag/v${version}
ManifestType: defaultLocale
ManifestVersion: ${MANIFEST_VERSION}
`
  return {
    [`${id}.yaml`]: versionManifest,
    [`${id}.installer.yaml`]: installerManifest,
    [`${id}.locale.en-US.yaml`]: localeManifest,
  }
}

function main() {
  const argv = process.argv.slice(2)
  const arg = (name) => { const i = argv.indexOf(name); return i >= 0 ? argv[i + 1] : undefined }
  const version = arg('--version')
  const assets = arg('--assets')
  const out = arg('--out')
  if (!version || !/^\d+\.\d+\.\d+$/.test(version) || !assets || !out) usage()

  const files = fs.readdirSync(assets)
  const installers = ARCHES.map(arch => {
    const name = installerFor(files, version, arch)
    if (!name) throw new Error(`no Windows ${arch} installer for ${version} in ${assets} (looked for TraceRoost-${version}-win-${arch}[-preview].exe)`)
    const sha256 = crypto.createHash('sha256').update(fs.readFileSync(path.join(assets, name))).digest('hex')
    return { arch, name, sha256, url: `https://github.com/${REPO}/releases/download/v${version}/${name}` }
  })

  const dir = path.join(out, 'manifests', 't', 'TraceRoost', 'TraceRoost', version)
  fs.mkdirSync(dir, { recursive: true })
  const releaseDate = new Date().toISOString().slice(0, 10)
  for (const [file, text] of Object.entries(manifests({ version, releaseDate, installers }))) {
    fs.writeFileSync(path.join(dir, file), text)
  }
  for (const i of installers) console.error(`${i.arch}: ${i.name} sha256 ${i.sha256}`)
  console.error(`Wrote ${dir}`)
  process.stdout.write(`${dir}\n`)
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try { main() } catch (e) {
    console.error(e instanceof Error ? e.message : e)
    process.exit(1)
  }
}
