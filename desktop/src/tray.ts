/**
 * The menu bar / system tray item.
 *
 * On macOS the icon is a *template* image: a black-and-transparent PNG whose name ends in
 * `Template`, which the system recolours for light and dark menu bars and for the highlighted
 * state. Shipping a coloured icon instead is the usual way a menu bar app ends up invisible on one
 * of the two appearances. Windows recolours nothing, so there the shell picks between two ICOs by
 * the taskbar's appearance and swaps when it changes — see trayIcon.ts for the rule.
 *
 * The menu's contents come from trayMenu.ts; this file is the Electron binding and the click
 * handlers, so that the labelling rules stay testable on their own.
 */

import { Menu, type MenuItemConstructorOptions, nativeImage, nativeTheme, Tray } from 'electron'
import { chooseTrayIcon } from './trayIcon'
import { type MenuItemId, type MenuModel } from './trayMenu'

export type TrayHandlers = Partial<Record<MenuItemId, () => void>>

export interface TrayController {
  update: (model: MenuModel) => void
  destroy: () => void
}

/** `assetDir` is desktop/build: trayTemplate.png (+@2x) for macOS, trayFor{Dark,Light}Taskbar.ico
 *  for Windows — all generated by scripts/make-icons.mjs. */
export function createTray(assetDir: string, handlers: TrayHandlers): TrayController {
  const loadImage = () => {
    const choice = chooseTrayIcon(assetDir, process.platform, nativeTheme.shouldUseDarkColorsForSystemIntegratedUI)
    const image = nativeImage.createFromPath(choice.file)
    // Marks it as a template so macOS, not us, decides the colour for the current menu bar.
    if (choice.template) image.setTemplateImage(true)
    return image
  }
  const tray = new Tray(loadImage())
  // The taskbar can switch appearance while the app runs (Settings, or a scheduled dark mode);
  // on macOS this fires too, but the choice there does not depend on the flag, so it is harmless.
  nativeTheme.on('updated', () => { tray.setImage(loadImage()) })

  const update = (model: MenuModel) => {
    tray.setToolTip(model.tooltip)
    const template: MenuItemConstructorOptions[] = model.items.map(item => {
      if ('separator' in item) return { type: 'separator' }
      return {
        label: item.label,
        enabled: item.enabled,
        ...(item.checked === undefined ? {} : { type: 'checkbox' as const, checked: item.checked }),
        ...(item.accessibilityLabel === undefined ? {} : { accessibilityLabel: item.accessibilityLabel }),
        click: item.isStatus ? undefined : handlers[item.id],
      }
    })
    tray.setContextMenu(Menu.buildFromTemplate(template))
  }

  return { update, destroy: () => tray.destroy() }
}
