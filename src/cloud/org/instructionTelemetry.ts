/**
 * Bridges local instruction-advisor state to the AL 08 wire records and the forwarding queue.
 *
 * Only `instruction_files` is sent: per repository, each instruction file's kind, whether it
 * exists, its path and content as keyed hashes, its line count and last-modified time. The
 * per-file read footprints (`file_footprints`) and Advisor suggestion events
 * (`suggestion_events`) this used to build are no longer sent — the cloud accepted and dropped
 * both, and data it doesn't use shouldn't leave the machine. `suggestedText`, `evidence` and
 * `title` never did.
 *
 * Lives in `src/cloud/org/`, not `src/cloud/forward/` — this is where `SessionSummaryCard` is read.
 */

import * as fs from 'fs'
import type { SuggestionCard } from '../../instructionAdvisor'
import { detectInstructionFiles } from '../../instructionFiles'
import { deriveRepoKey } from '../../repoKey'
import { buildInstructionFileState } from '../forward/buildInstructionTelemetry'
import type { InstructionFileKind, RollupPayload } from '../forward/schema'
import { SCHEMA_VERSION } from '../forward/schema'
import { repoKeyFingerprint } from '../../repoKey'
import { ForwardQueue } from '../forward/queue'
import { loadCredentials } from './credentials'
import type { SessionSummaryCard } from '../../summarizers/summarizerTypes'

const KIND_MAP: Record<string, InstructionFileKind> = {
  claude_code: 'claude_md',
  codex: 'agents_md',
  copilot: 'copilot_instructions',
}

/** What the ledger remembers about a suggestion whose full card the Advisor may no longer
 *  regenerate. Only the id, the enums — never the prose. */
export type LedgerCard = { id: string; category?: SuggestionCard['category']; priority?: SuggestionCard['priority']; targetAgents?: string[] }

export interface SuggestionLedger {
  /** Raw suggestion ids that have been applied, with their apply time. `card` lets an applied
   *  suggestion still emit an event after it stops being regenerated by the Advisor. */
  applied: Array<{ id: string; atIso: string; card?: LedgerCard }>
  dismissed: Array<{ id: string; atIso: string }>
  reverted: Array<{ id: string; atIso: string }>
}

export const EMPTY_LEDGER: SuggestionLedger = { applied: [], dismissed: [], reverted: [] }

/**
 * Builds the instruction-telemetry portion of a rollup for one repository. Returns `null` when
 * the repo can't be keyed. Pure — no queueing, no network. `sessions` and `ledger` are no longer
 * read (they fed the dropped `file_footprints` / `suggestion_events`); kept so the hosts' call
 * sites stay as they are.
 */
export async function buildInstructionRollup(
  workspace: string,
  _sessions: SessionSummaryCard[],
  _ledger: SuggestionLedger,
): Promise<RollupPayload | null> {
  const creds = loadCredentials()
  const rk = await deriveRepoKey(workspace, creds?.orgId ?? 'unlinked-preview')
  if (!rk.ok) return null
  const ctx = rk.ctx

  const files = detectInstructionFiles(workspace).map(f => {
    let lineCount = 0
    let lastModifiedIso: string | undefined
    if (f.exists) {
      lineCount = f.content.split('\n').length
      try { lastModifiedIso = fs.statSync(f.filePath).mtime.toISOString() } catch { /* ignore */ }
    }
    return buildInstructionFileState({
      present: f.exists,
      kind: KIND_MAP[f.agent] ?? 'other',
      path: f.relativePath,
      content: f.content,
      lineCount,
      lastModifiedIso,
    }, ctx)
  })

  const payload: RollupPayload = {
    schema_version: SCHEMA_VERSION,
    repo_key_fp: repoKeyFingerprint(ctx),
  }
  if (files.length > 0) payload.instruction_files = files
  return payload
}

/**
 * Builds the instruction rollup for `workspace` and appends it to the forwarding queue — a hard
 * no-op unless an org is linked.
 */
export async function maybeEnqueueInstructionTelemetry(
  workspace: string,
  sessions: SessionSummaryCard[],
  ledger: SuggestionLedger,
): Promise<boolean> {
  if (!loadCredentials()) return false
  const payload = await buildInstructionRollup(workspace, sessions, ledger)
  if (!payload || !payload.instruction_files) return false
  return new ForwardQueue().enqueue(payload)
}
