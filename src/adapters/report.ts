/**
 * "Report this": a prefilled GitHub issue about an agent version TraceRoost doesn't fully
 * recognize. The body is built here, locally, from adapter health alone — agent, versions, OS,
 * unknown names with counts, and one structural fingerprint per name (key names and value types,
 * never values). The dashboard and `traceroost doctor` show it in full before anything opens; the
 * user's browser files it, or doesn't. No network call is made from TraceRoost.
 */

import type { AgentHealthRow } from './health'

export const REPORT_REPO_URL = 'https://github.com/traceroost/core'

// GitHub rejects a /issues/new URL much past 8 KB; fingerprints are dropped first to fit.
const MAX_URL = 7500

export interface AgentReport {
  title: string
  body: string
  /** `${REPORT_REPO_URL}/issues/new?…` with title, body and label filled in. */
  url: string
}

export function buildAgentReport(row: AgentHealthRow, version: string, env: { traceroostVersion: string; os: string }): AgentReport | null {
  const v = row.versions.find(x => x.version === version)
  if (!v || v.unknown === 0) return null
  const title = `${row.label} ${version}: unrecognized data`
  const names = Object.entries(v.unknownNames).sort((a, b) => b[1] - a[1])
  const head = [
    `**Agent:** ${row.label}`,
    `**Agent version:** ${version}`,
    `**TraceRoost version:** ${env.traceroostVersion}`,
    `**OS:** ${env.os}`,
    `**Records:** ${v.known} read, ${v.ignored} skipped on purpose, ${v.unknown} unrecognized`,
    '',
    '### Unrecognized records',
    '',
    '| Name | Count |',
    '|---|---|',
    ...names.map(([n, c]) => `| \`${n.replace(/[|`]/g, '')}\` | ${c} |`),
  ]
  const shapes = names.filter(([n]) => v.fingerprints[n] !== undefined).map(([n]) =>
    `\`${n.replace(/`/g, '')}\`:\n\`\`\`json\n${JSON.stringify(v.fingerprints[n], null, 1)}\n\`\`\``)
  const foot = ['', '_Generated by TraceRoost from key names, value types and counts only, no values from your logs._']
  const urlFor = (body: string) => `${REPORT_REPO_URL}/issues/new?${new URLSearchParams({ title, body, labels: 'agent-format' }).toString()}`

  let body = ''
  for (let keep = shapes.length; keep >= 0; keep--) {
    const shapeLines = keep > 0 ? ['', '### Structure of one unrecognized record per name (key names and value types)', '', ...shapes.slice(0, keep)] : []
    const omitted = shapes.length - keep
    body = [...head, ...shapeLines, ...(omitted > 0 ? ['', `_${omitted} more structure${omitted === 1 ? '' : 's'} left out to fit the issue form._`] : []), ...foot].join('\n')
    if (urlFor(body).length <= MAX_URL) break
  }
  return { title, body, url: urlFor(body) }
}
