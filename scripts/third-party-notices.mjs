#!/usr/bin/env node
// Writes THIRD_PARTY_NOTICES.md — the copyright and license notice of every third-party package
// whose code ships inside TraceRoost's bundles:
//
//   node scripts/third-party-notices.mjs           regenerate THIRD_PARTY_NOTICES.md
//   node scripts/third-party-notices.mjs --check   exit 1 if it is out of date (CI)
//
// Every dependency is bundled (package.json has no `dependencies`), so the npm package, the VSIX
// and the Docker image carry other projects' code with no node_modules/ beside it, and MIT, ISC
// and BSD all ask for their notice to travel with copies. Which packages ship is read from
// esbuild's own metafile (a production build of the full edition — the superset of core), not
// from package.json, so a new transitive dependency can't be missed. dist/sql-wasm.{js,wasm} are
// copied from sql.js as files, so sql.js is always listed.

import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT = path.join(root, 'THIRD_PARTY_NOTICES.md')
const ALWAYS = ['sql.js']
const LICENSE_FILE = /^(licen[cs]e|copying|notice)(\.(md|txt|markdown))?$/i

/** `node_modules/.pnpm/a@1/node_modules/@scope/name/lib/x.js` → its package directory. */
export function packageDirOf(input) {
  const parts = input.split(/[\\/]/)
  const i = parts.lastIndexOf('node_modules')
  if (i < 0 || i + 1 >= parts.length) return null
  const take = parts[i + 1].startsWith('@') ? 3 : 2
  return parts.slice(0, i + take).join('/')
}

function bundleInputs() {
  const tmp = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'tr-notices-')), 'inputs.json')
  execFileSync(process.execPath, ['esbuild.js', '--production', '--edition=full'], {
    cwd: root,
    env: { ...process.env, TRACEROOST_BUNDLE_INPUTS: tmp },
    stdio: ['ignore', 'ignore', 'inherit'],
  })
  return JSON.parse(fs.readFileSync(tmp, 'utf-8'))
}

function licenseText(dir) {
  const file = fs.readdirSync(dir).filter((f) => LICENSE_FILE.test(f)).sort()[0]
  // LF only: a package's CRLF license file would otherwise differ from git's normalized checkout.
  return file ? fs.readFileSync(path.join(dir, file), 'utf-8').replace(/\r\n?/g, '\n').trim() : null
}

function describe(dir) {
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf-8'))
  const license = typeof pkg.license === 'string' ? pkg.license : pkg.license?.type ?? 'UNKNOWN'
  const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url
  return { name: pkg.name, version: pkg.version, license, homepage: pkg.homepage ?? repo ?? null, text: licenseText(dir) }
}

export function render(packages) {
  const lines = [
    '# Third-party notices',
    '',
    'TraceRoost bundles the following open source packages into its published builds (the npm',
    'package, the VS Code extension and the Docker image). Each is used under its own license,',
    'reproduced below. TraceRoost’s own licenses are in LICENSE and NOTICE.md.',
    '',
    'Generated by `node scripts/third-party-notices.mjs` — don’t edit by hand.',
    '',
    '| Package | Version | License |',
    '| --- | --- | --- |',
    ...packages.map((p) => `| ${p.name} | ${p.version} | ${p.license} |`),
    '',
  ]
  for (const p of packages) {
    lines.push('---', '', `## ${p.name} ${p.version}`, '', `License: ${p.license}${p.homepage ? `  \nSource: ${p.homepage}` : ''}`, '')
    lines.push(p.text ? '```text\n' + p.text + '\n```' : `_No license file ships in the package; its package.json declares ${p.license}._`, '')
  }
  return lines.join('\n')
}

function main() {
  const check = process.argv.includes('--check')
  const dirs = new Set()
  for (const input of bundleInputs()) {
    const dir = packageDirOf(input)
    if (dir) dirs.add(path.resolve(root, dir))
  }
  for (const name of ALWAYS) dirs.add(fs.realpathSync(path.join(root, 'node_modules', name)))

  const byName = new Map()
  for (const dir of dirs) {
    const p = describe(fs.realpathSync(dir))
    byName.set(`${p.name}@${p.version}`, p)
  }
  const packages = [...byName.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))
  const missing = packages.filter((p) => !p.text).map((p) => p.name)
  const text = render(packages)

  if (check) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf-8') : ''
    if (current !== text) {
      console.error('THIRD_PARTY_NOTICES.md is out of date — run `node scripts/third-party-notices.mjs` and commit it.')
      process.exit(1)
    }
    console.log(`THIRD_PARTY_NOTICES.md is current (${packages.length} packages).`)
    return
  }
  fs.writeFileSync(OUT, text)
  console.log(`Wrote THIRD_PARTY_NOTICES.md (${packages.length} packages${missing.length ? `; no license file in: ${missing.join(', ')}` : ''}).`)
}

if (import.meta.url === `file://${process.argv[1]}`) main()
