#!/usr/bin/env node
// Writes the Homebrew formula for a published npm version of traceroost:
//
//   node scripts/homebrew-formula.mjs 0.19.0                    print Formula/traceroost.rb
//   node scripts/homebrew-formula.mjs 0.19.0 --out <file>       write it to <file>
//   node scripts/homebrew-formula.mjs --tarball <file.tgz> [--out <file>]
//                                                               a formula for a local `npm pack`
//                                                               tarball (file:// URL), to try a
//                                                               build before it is published —
//                                                               scripts/homebrew-local.sh uses it
//
// The formula installs the exact tarball npm serves (its sha256 is computed here from the
// download, so the formula can only ever install what was published), with Homebrew's own `node`.
// The release workflow runs this after `npm publish` and commits the result to the
// traceroost/homebrew-tap repository (`brew install traceroost/tap/traceroost`); see
// runbooks/RELEASING.md → "Homebrew". The registry can take a moment to serve a fresh publish, so
// the download is retried.
//
// The background service is TraceRoost's own (`traceroost service install` — launchd on macOS,
// systemd --user on Linux), exactly as for an npm install; the formula deliberately has no
// `service do` block, so there is never a second, `brew services`-managed copy competing for the
// same ports. `traceroost service install` / `update` run `brew upgrade` for a Homebrew install
// (standalone/service/homebrew.ts).

import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'

const PACKAGE = 'traceroost'

function usage() {
  console.error('usage: node scripts/homebrew-formula.mjs <version> [--out <file>]\n       node scripts/homebrew-formula.mjs --tarball <file.tgz> [--out <file>]')
  process.exit(2)
}

async function fetchWithRetry(url, attempts = 10) {
  for (let i = 1; ; i++) {
    const res = await fetch(url)
    if (res.ok) return res
    if (i >= attempts || (res.status !== 404 && res.status < 500)) {
      throw new Error(`${url}: HTTP ${res.status}`)
    }
    await new Promise((r) => setTimeout(r, 15_000))
  }
}

/** The npm `license` field as Homebrew's `license` DSL: an SPDX id, or `all_of:` for an
 *  `(A AND B)` expression. */
export function brewLicense(spdx) {
  const ids = String(spdx ?? '').replace(/[()]/g, '').split(/\s+AND\s+/).map((s) => s.trim()).filter(Boolean)
  if (ids.length === 0) return null
  if (ids.length === 1) return `"${ids[0]}"`
  return `all_of: [${ids.map((id) => `"${id}"`).join(', ')}]`
}

export function formula({ version, url, sha256, license }) {
  return `# Generated by traceroost/core scripts/homebrew-formula.mjs for ${PACKAGE} ${version} — don't edit by hand.
class Traceroost < Formula
  desc "Local monitoring for AI coding agents: traces, cost and stuck-agent signals"
  homepage "https://traceroost.com"
  url "${url}"
  sha256 "${sha256}"
${license ? `  license ${license}\n` : ''}
  depends_on "node"

  # With Homebrew's node, an earlier \`npm install -g traceroost\` owns bin/traceroost in the same
  # prefix; take it over so switching from npm needs no manual step (\`traceroost service install\`
  # then moves the background service onto this copy).
  link_overwrite "bin/traceroost"

  def install
    system "npm", "install", *std_npm_args
    bin.install_symlink libexec.glob("bin/*")
  end

  def caveats
    <<~EOS
      Run TraceRoost in the background (starts at login, restarts if it crashes;
      if you had it from npm before, this moves the service onto this copy):
        traceroost service install

      Upgrade later, service included:
        traceroost service update

      Or run it in this terminal only:
        traceroost
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/traceroost --version")
  end
end
`
}

async function main() {
  const argv = process.argv.slice(2)
  const outAt = argv.indexOf('--out')
  const out = outAt >= 0 ? argv[outAt + 1] : undefined
  if (outAt >= 0 && !out) usage()

  const tarAt = argv.indexOf('--tarball')
  if (tarAt >= 0) {
    const file = argv[tarAt + 1]
    if (!file || !fs.existsSync(file)) usage()
    const abs = path.resolve(file)
    const m = path.basename(abs).match(/^traceroost-(\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?)\.tgz$/)
    if (!m) throw new Error(`expected an npm pack tarball named traceroost-<version>.tgz, got ${path.basename(abs)}`)
    const sha256 = crypto.createHash('sha256').update(fs.readFileSync(abs)).digest('hex')
    const pkg = JSON.parse(fs.readFileSync(new URL('../package.json', import.meta.url), 'utf8'))
    const text = formula({ version: m[1], url: `file://${abs}`, sha256, license: brewLicense(pkg.license) })
    if (out) {
      fs.writeFileSync(out, text)
      console.error(`Wrote ${out} (local ${path.basename(abs)}, sha256 ${sha256})`)
    } else {
      process.stdout.write(text)
    }
    return
  }

  const version = argv[0]
  if (!version || !/^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$/.test(version)) usage()

  const meta = await (await fetchWithRetry(`https://registry.npmjs.org/${PACKAGE}/${version}`)).json()
  const url = meta.dist?.tarball
  if (!url) throw new Error(`npm has no tarball for ${PACKAGE}@${version}`)
  const tarball = Buffer.from(await (await fetchWithRetry(url)).arrayBuffer())
  const sha256 = crypto.createHash('sha256').update(tarball).digest('hex')

  const text = formula({ version, url, sha256, license: brewLicense(meta.license) })
  if (out) {
    fs.writeFileSync(out, text)
    console.error(`Wrote ${out} (${PACKAGE} ${version}, sha256 ${sha256})`)
  } else {
    process.stdout.write(text)
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch((e) => {
    console.error(e instanceof Error ? e.message : e)
    process.exit(1)
  })
}
